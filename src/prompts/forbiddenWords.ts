/**
 * 获取所有已启用的禁用词（扁平列表）
 */
export function getEnabledForbiddenWords(): string[] {
  return forbiddenWordCategories
    .filter((c) => c.enabled)
    .flatMap((c) => c.words);
}

/**
 * 获取所有禁用词（包括未启用的）
 */
export function getAllForbiddenWords(): string[] {
  return forbiddenWordCategories.flatMap((c) => c.words);
}

/**
 * 检查文本中是否包含禁用词
 * @param text 待检查文本
 * @param categories 可选，指定检查的分类（不传则检查所有已启用的分类）
 * @returns 匹配到的禁用词列表，包含禁用词和所属分类
 */
export function checkForbiddenWords(
  text: string,
  categories?: string[],
): Array<{ word: string; category: string }> {
  const targetCategories = categories
    ? forbiddenWordCategories.filter((c) => categories.includes(c.name))
    : forbiddenWordCategories.filter((c) => c.enabled);

  const matches: Array<{ word: string; category: string }> = [];

  for (const category of targetCategories) {
    for (const word of category.words) {
      if (text.includes(word)) {
        matches.push({ word, category: category.name });
      }
    }
  }

  return matches;
}

/**
 * 生成用于提示词的禁用词说明文本
 * @param categories 可选，指定包含的分类
 */
export function generateForbiddenWordsPrompt(categories?: string[]): string {
  const targetCategories = categories
    ? forbiddenWordCategories.filter((c) => categories.includes(c.name))
    : forbiddenWordCategories.filter((c) => c.enabled);

  let prompt = '【禁用词表 - 以下词汇和表达严禁在正文中出现】\n\n';

  for (const category of targetCategories) {
    prompt += `■ ${category.name}（${category.description}）：\n`;
    prompt += category.words.map((w) => `  - ${w}`).join('\n');
    prompt += '\n\n';
  }

  prompt += `以上共 ${targetCategories.flatMap((c) => c.words).length} 个禁用词/表达。`;
  prompt += '如果发现已生成的文本中包含这些词汇，必须立即替换为更具体、更生动的表达。';

  return prompt;
}
