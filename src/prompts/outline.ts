/**
 * 审查已生成的大纲
 */
export const outlineReviewPrompt = `【审查第{volumeNumber}卷大纲】

请从以下维度审查第{volumeNumber}卷的大纲，指出问题并给出修改建议。

## 项目方案
{projectContent}

## 待审查大纲
{outlineContent}

## 审查维度

### 1. 结构完整性
- setup → build → climax → fallout 的节奏是否合理？
- 是否有"空转"章节（不推进剧情也不建立角色）？
- 高潮章的铺垫是否充分？

### 2. 悬念管理
- 悬念密度是否有起伏？
- 伏笔是否都有回收计划？
- 是否有"遗忘"的伏笔（埋了但没打算回收）？
- 章末钩子是否都在后续章节中有回应？

### 3. 角色一致性
- 角色的行为是否符合其设定？
- 角色的成长弧线是否连贯？
- 是否有角色"工具人化"（只在需要时出现）？

### 4. 信息控制
- 信息释放的节奏是否合理？
- 是否有"信息倾倒"（一次性释放太多信息）？
- 认知颠覆是否有足够铺垫？

### 5. 节奏控制
- 章节长度分配是否合理？
- 是否有连续多章节奏相同（都是铺垫或都是高潮）？
- 转场是否自然？

### 6. 与项目方案的一致性
- 大纲是否偏离了项目方案的核心设定？
- 类型基调是否一致？
- 终局愿景是否在本卷中有推进？

请以表格形式输出审查结果，包含：维度、评分（1-5）、问题描述、修改建议。`;
