/**
 * 获取风格对象
 */
export function getStyle(styleId: string): StyleRule | undefined {
  return styles[styleId];
}

/**
 * 获取所有可用风格列表
 */
export function getAvailableStyles(): Array<{ id: string; name: string; description: string }> {
  return Object.values(styles).map((s) => ({
    id: s.id,
    name: s.name,
    description: s.description,
  }));
}

/**
 * 获取风格的系统提示词
 */
export function getStyleSystemPrompt(styleId: string): string {
  const style = styles[styleId];
  if (!style) {
    return '';
  }
  return style.systemPrompt;
}

/**
 * 将风格规则嵌入到写作提示词中
 */
export function embedStyleRules(styleId: string, basePrompt: string): string {
  const style = styles[styleId];
  if (!style) {
    return basePrompt;
  }

  const styleSection = `
【风格要求：${style.name}】

${style.systemPrompt}

【风格检查清单 - 生成后自查】
- 句式：${style.sentenceRules.slice(0, 3).join('；')}
- 描写：${style.descriptionRules.slice(0, 3).join('；')}
- 对话：${style.dialogueRules.slice(0, 3).join('；')}
- 情绪：${style.emotionRules.slice(0, 3).join('；')}
- 节奏：平均句长${style.pacing.avgSentenceLength}，段落${style.pacing.paragraphLength}
`;

  return styleSection + '\n\n' + basePrompt;
}
