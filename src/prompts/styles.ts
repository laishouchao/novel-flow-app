/**
 * 风格引擎提示词
 *
 * 将 novel-flow 的 3 种预设风格转化为结构化的风格规则对象。
 * 每种风格包含：sentenceRules, descriptionRules, dialogueRules, emotionRules, forbiddenPatterns, forbiddenWords
 *
 * 风格列表：
 * - coldRealism: 冷白描（余华/海明威风格）
 * - systemPower: 系统爽文（升级流/系统流）
 * - bizarreSuspense: 怪诞悬疑（规则怪谈/克苏鲁）
 */

// ============================================================
// 类型定义
// ============================================================

export interface StyleRule {
  /** 风格标识 */
  id: string;
  /** 风格名称 */
  name: string;
  /** 风格描述 */
  description: string;
  /** 代表作家/作品 */
  representatives: string[];
  /** 句式规则 */
  sentenceRules: string[];
  /** 描写规则 */
  descriptionRules: string[];
  /** 对话规则 */
  dialogueRules: string[];
  /** 情绪表达规则 */
  emotionRules: string[];
  /** 禁用的句式模式 */
  forbiddenPatterns: string[];
  /** 风格专属禁用词 */
  forbiddenWords: string[];
  /** 节奏控制 */
  pacing: {
    /** 平均句长（字数） */
    avgSentenceLength: string;
    /** 段落长度偏好 */
    paragraphLength: string;
    /** 对话与叙述比例 */
    dialogueRatio: string;
  };
  /** 完整的风格指导提示词 */
  systemPrompt: string;
}

