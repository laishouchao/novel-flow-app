/**
 * 填充定稿提示词模板中的变量
 */
export function fillFinalizationTemplate(
  template: string,
  variables: Record<string, string>,
): string {
  let filled = template;
  for (const [key, value] of Object.entries(variables)) {
    filled = filled.replace(new RegExp(`\\{${key}\\}`, 'g'), value);
  }
  return filled;
}
